<?php

/**
 * Bundles phpEZ into a single phpez.php file.
 *
 * Starting from sys/boot.php, inlines every `require_once('xxx.php');` call
 * (plain lowercase filename, no path) with the referenced file's contents,
 * stripping its leading `<?php` tag. Requires using dynamic paths (e.g.
 * __DIR__ concatenation or variables) are left untouched.
 *
 * Usage: php build/package.php [output-path]
 */

$root = dirname(__DIR__);
$sysDir = $root . '/sys';
$entry = $sysDir . '/boot.php';
$out = $argv[1] ?? $root . '/phpez.php';

function strip_open_tag(string $code): string
{
  return preg_replace('/^\s*<\?php\s*/', '', $code, 1);
}

function inline_requires(string $path, string $dir, array &$seen): string
{
  $code = strip_open_tag(file_get_contents($path));

  return preg_replace_callback(
    '/require_once\(\'([a-z]+\.php)\'\);/',
    function ($m) use ($dir, &$seen) {
      $file = $m[1];
      // already inlined elsewhere, drop the duplicate require
      if (isset($seen[$file])) {
        return '';
      }
      $seen[$file] = true;
      return inline_requires($dir . '/' . $file, $dir, $seen);
    },
    $code
  );
}

$seen = ['boot.php' => true];
$bundle = inline_requires($entry, $sysDir, $seen);

$version = getenv('GITHUB_REF_NAME') ?: 'dev';
$header = "<?php\n\n/**\n * phpEZ {$version} - single-file bundle.\n * Auto-generated by build/package.php, do not edit directly.\n */\n\n";

file_put_contents($out, $header . $bundle);

echo "Bundled " . basename($out) . " (" . filesize($out) . " bytes)\n";
